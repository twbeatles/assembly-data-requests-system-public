def expand(term: str) -> list:
    """한 낱말의 동의어 목록. 자기 자신이 항상 먼저 온다."""
    key = str(term or "").strip().lower()
    if not key:
        return []
    variants = [key]
    for s in SYNONYMS.get(key, ()):
        low = str(s).lower()
        if low not in variants:
            variants.append(low)
    return variants


def to_json(indent=2) -> str:
    """대시보드 JS에 주입할 JSON. `</`를 이스케이프해 script 태그를 닫지 못하게 한다."""
    import json as _json
    return _json.dumps(SYNONYMS, ensure_ascii=False, indent=indent).replace("</", "<\\/")
